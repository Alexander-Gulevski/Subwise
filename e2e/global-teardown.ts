import { disconnect } from './helpers';

/**
 * Закрытие соединений после всего прогона.
 *
 * Раньше каждый файл тестов закрывал соединение сам в afterAll,
 * но клиент Prisma один на весь процесс: закрытие в конце одного
 * файла обрывало его под ногами у следующего. Отсюда плавающие
 * падения, которые не воспроизводились при запуске файла отдельно.
 */
export default async function globalTeardown(): Promise<void> {
  await disconnect();
}
